#!/usr/bin/env bash
# METHOD_NOTES 2.80: more ways of hiding PART of a game in training (the family that passed three times on 2026-11-14: opening
# dropout, ply masking, dropout), each alone on top of the symmetry augmentation; held-out folds 1 and 2, the x2 data, against yse:
#   ra  the played POINT of up to 30 % of the plies hidden (board vectors kept)        --mask-pos 0.3
#   rb  whole plies dropped at random, up to 30 % (board vector and point)             --mask 0.3 --mask-both
#   rc  every input dimension replaced by its mean with probability 0.25, per game     --chan-drop 0.25
#   rd  the tail of the game hidden from a random ply K in 100..220, in 30 % of games  --drop-tail 0.3
# Result results/final/v2_sim14r.json. Do not edit this file while a job runs it; the body is a function called with exit.
set -uo pipefail
main() {
  local R2=/home/u2507115/BK_AICUP_2026-2 X=/work/u2507115/ext_fox S=/work/u2507115/pid_v2/seqnet
  local X2="--ext-ply $X/pilot/ply $X/scale1/ply_a --ext-select $X/pilot/select.csv $X/scale1/select.csv"
  local C="--steps 20000 --horizon 60000 --ext-share 0.5 --no-state --sym-aug"
  local specs=() v t
  for v in 1 2; do
    specs+=("$v ra $C --mask-pos 0.3" "$v rb $C --mask 0.3 --mask-both" "$v rc $C --chan-drop 0.25" "$v rd $C --drop-tail 0.3")
  done
  bash $R2/scripts/nano4/pid_seq_train_fork.sh "$X2" "${specs[@]}"
  for t in rae rbe rce rde; do
    python -I $R2/scripts/pid_v2_seq_embed.py --stage folds --folds 1 2 --ckpt-dir $S --ckpt-suffix _$t --name _n$t --out $R2/data/seq
  done
  python -I $R2/scripts/pid_v2_sim14.py --names yse=_nyse zme=_nzme zoe=_nzoe rae=_nrae rbe=_nrbe rce=_nrce rde=_nrde --ref yse --folds 1 2 --out $R2/results/final/v2_sim14r.json
}
main "$@"; exit $?
