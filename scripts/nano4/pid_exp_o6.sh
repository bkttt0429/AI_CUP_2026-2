#                         o6SMs0-3 : symmetry + ply masking 0.3 + opening hidden in 30 % of the games (the two together: new)
#   pid_exp_o6.sh combo   held-out test of the combinations (folds 1 and 2, the x2 data, against yse; with zoe and zme):
#                         ca = opening 0.3 + masking 0.3, cb = ca + dropout 0.2, cc = masking 0.3 + dropout 0.2, cd = masking 0.5
# Do not edit this file while a job runs it (METHOD_NOTES 2.74); the body is a function called on the last line with exit.
set -uo pipefail
main() {
  local R2=/home/u2507115/BK_AICUP_2026-2 X=/work/u2507115/ext_fox S=/work/u2507115/pid_v2/seqnet
  local DATA4="--ext-ply $X/pilot/ply $X/scale1/ply_a $X/scale1/ply_b $R2/data/ext_ply/scale1_c $R2/data/ext_ply/scale2_top $R2/data/ext_ply/scale2_5d $X/scale3/ply --ext-select $X/pilot/select.csv $X/scale1/select.csv $X/scale2_top/select.csv $X/scale2_5d/select.csv $X/scale3/select.csv"
  local X2="--ext-ply $X/pilot/ply $X/scale1/ply_a --ext-select $X/pilot/select.csv $X/scale1/select.csv"
  local C="--steps 20000 --horizon 60000 --ext-share 0.5 --no-state --sym-aug"
  local specs=() k v t
  case $1 in
    mask)
      for k in 0 1 2 3; do specs+=("-1 o6Ss$k $C --mask 0.3 --seed $k"); done
      for k in 0 1 2 3; do specs+=("-1 o6SMs$k $C --mask 0.3 --drop-open 0.3 --seed $k"); done
      bash $R2/scripts/nano4/pid_seq_train_fork.sh "$DATA4" "${specs[@]}" ;;
    combo)
      for v in 1 2; do
        specs+=("$v ca $C --drop-open 0.3 --mask 0.3" "$v cb $C --drop-open 0.3 --mask 0.3 --drop 0.2" "$v cc $C --mask 0.3 --drop 0.2" "$v cd $C --mask 0.5")
      done
      bash $R2/scripts/nano4/pid_seq_train_fork.sh "$X2" "${specs[@]}"
      for t in cae cbe cce cde; do
        python -I $R2/scripts/pid_v2_seq_embed.py --stage folds --folds 1 2 --ckpt-dir $S --ckpt-suffix _$t --name _n$t --out $R2/data/seq
      done
      python -I $R2/scripts/pid_v2_sim14.py --names yse=_nyse zoe=_nzoe zme=_nzme cae=_ncae cbe=_ncbe cce=_ncce cde=_ncde --ref yse --folds 1 2 --out $R2/results/final/v2_sim14c2.json
      python -I $R2/scripts/pid_v2_sim14.py --names zme=_nzme zoe=_nzoe cae=_ncae cbe=_ncbe cce=_ncce cde=_ncde --ref zme --folds 1 2 --out $R2/results/final/v2_sim14c2m.json ;;
    *) echo "unknown case $1"; return 2 ;;
  esac
}
main "$@"; exit $?
